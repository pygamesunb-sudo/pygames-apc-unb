from app.models.ready_exercises import ReadyExample, ReadyExercise


def _exercise(
    external_id: str,
    title: str,
    topic: str,
    topics: list[str],
    difficulty: str,
    level: int,
    statement: str,
    input_description: str,
    output_description: str,
    examples: list[tuple[str, str]],
    hints: list[str],
) -> ReadyExercise:
    return ReadyExercise(
        id=f"pygames_{external_id}",
        external_id=external_id,
        source="pygames",
        title=title,
        statement=statement,
        topic=topic,
        topics=[topic, *topics],
        difficulty=difficulty,  # type: ignore[arg-type]
        level=level,
        input_description=input_description,
        output_description=output_description,
        examples=[ReadyExample(input=sample_input, output=sample_output) for sample_input, sample_output in examples],
        hints=hints,
    )


